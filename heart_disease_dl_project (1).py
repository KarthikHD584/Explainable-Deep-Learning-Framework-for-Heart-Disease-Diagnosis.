def make_datasets_flat(data_dir):
    train_ds = tf.keras.utils.image_dataset_from_directory(
        data_dir, validation_split=0.3, subset="training", seed=SEED,
        image_size=IMG_SIZE, batch_size=BATCH_SIZE, label_mode="binary"
    )
    val_test_ds = tf.keras.utils.image_dataset_from_directory(
        data_dir, validation_split=0.3, subset="validation", seed=SEED,
        image_size=IMG_SIZE, batch_size=BATCH_SIZE, label_mode="binary"
    )
    class_names = train_ds.class_names
    val_batches = tf.data.experimental.cardinality(val_test_ds)
    test_ds = val_test_ds.take(val_batches // 2)
    val_ds = val_test_ds.skip(val_batches // 2)
    return train_ds, val_ds, test_ds, class_names

def make_datasets_presplit(data_dir):
    train_dir = os.path.join(data_dir, "train")
    test_dir = os.path.join(data_dir, "test")
    val_dir = os.path.join(data_dir, "val")
    if not os.path.isdir(val_dir):
        val_dir = os.path.join(data_dir, "validation")

    train_ds = tf.keras.utils.image_dataset_from_directory(
        train_dir, image_size=IMG_SIZE, batch_size=BATCH_SIZE,
        label_mode="binary", seed=SEED
    )
    class_names = train_ds.class_names

    if os.path.isdir(val_dir):
        val_ds = tf.keras.utils.image_dataset_from_directory(
            val_dir, image_size=IMG_SIZE, batch_size=BATCH_SIZE,
            label_mode="binary", seed=SEED
        )
    else:
        val_batches = tf.data.experimental.cardinality(train_ds)
        val_ds = train_ds.take(val_batches // 5)
        train_ds = train_ds.skip(val_batches // 5)

    test_ds = tf.keras.utils.image_dataset_from_directory(
        test_dir, image_size=IMG_SIZE, batch_size=BATCH_SIZE,
        label_mode="binary", seed=SEED
    )
    return train_ds, val_ds, test_ds, class_names


